#ifndef WALKDROID_SONY_DSF_NATIVE_OWNED_H
#define WALKDROID_SONY_DSF_NATIVE_OWNED_H
#include "sony_audio_dsf_route.h"
#include "sony_audio_dsd_power_platform.h"
struct sony_dsf_native_owned;
#define SONY_DSF_NATIVE_OWNED_EXPLICIT_START 0x444e4f31u
struct sony_dsf_native_owned_cleanup {
    struct sony_dsf_native_playback_cleanup playback;
    struct sony_dsf_process_exit dsf;
    struct sony_dsd_sink_process_exit native;
    struct sony_dsd_power_platform_state power;
    unsigned resources_before[SONY_DSD_RESOURCE_COUNT],resources_after[SONY_DSD_RESOURCE_COUNT];
    int dsf_shutdown,native_shutdown,resource_readback,resource_mismatch,platform_destroy,route;
};
struct sony_dsf_native_owned_controls {uint64_t generation;struct wdf_controls acknowledged;};
/* Inactive, explicit hardware-capable integration. Actual BTL/mode1 only; no
 * conversion fallback, device choice, mounting, Android authorization or auto
 * activation. Both build-pinned roots are read-only. Only DSF /data/config is
 * a bind mount of the supplied NEW private 0700 directory/current.bin absent;
 * native configuration is explicit CFW/latency scope, never a second store.
 * Caller prepares the exact private nodes. This controller owns native power,
 * exact workers, file lifecycle, route, commands and original hardware volume.
 * All other writers/HAL must participate in global ownership. Bringup guard and
 * disabled deep-idle remain mandatory; no suspend experiment here.
 * Single serialized controller, including cancel. Borrowed fds unmodified.
 * Every non-NULL result requires close after success OR partial start failure.
 * Never replace an instance while cleanup/source/child/resources are retained. */
int sony_dsf_native_owned_start(struct sony_dsf_native_owned **,unsigned activation,int dsf_root,int native_root,
    int log_fd,const char *config_directory,int media_directory,const char *basename,uint64_t max_bytes,
    const struct sony_dsd_controls *,unsigned renderer_latency,unsigned native_low_latency);
int sony_dsf_native_owned_step(struct sony_dsf_native_owned *);
int sony_dsf_native_owned_state(struct sony_dsf_native_owned *,struct sony_dsf_native_playback_state *);
/* DAC/save receipts generated by this exact owner, not WDF DSP acknowledgements.
 * Only master volume can change. OLD+pending until next actual playback step
 * checks/commits the route; no injected samples or extra audio step at EOF.
 * Caller generation/revision/unsupported targets fail without sealing a
 * healthy session; admitted hardware/save uncertainty quiesces and seals. */
int sony_dsf_native_owned_get_controls(struct sony_dsf_native_owned *,struct sony_dsf_native_owned_controls *);
int sony_dsf_native_owned_stage_controls(struct sony_dsf_native_owned *,uint64_t generation,unsigned revision,
    const struct sony_dsd_live_controls *,struct sony_dsf_native_owned_controls *);
int sony_dsf_native_owned_enable_commands(struct sony_dsf_native_owned *);
int sony_dsf_native_owned_poll_commands(struct sony_dsf_native_owned *);
void sony_dsf_native_owned_cancel(struct sony_dsf_native_owned *);
/* Stop command admission -> quiesce/close file -> shutdown/reap BOTH exact
 * workers with native power service still alive -> independent prior-resource
 * and PCM/route checks -> global owner finish. Unknown Release/lost child or
 * retained source keeps this object AND borrowed power authority alive. No
 * manual owner reset, arbitrary PID kill, replay, retry of unknown release or
 * inference of CLEAN from exit alone. Cleanup status is separate from earlier
 * playback failure and does not prove physical DAC consumption. */
int sony_dsf_native_owned_close(struct sony_dsf_native_owned **,struct sony_dsf_native_owned_cleanup *);
#endif
